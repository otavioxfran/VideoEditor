"""Sound design for the final video: synthesized effects on layers and ducked music.

Effects are generated by FFmpeg from formulas (no downloaded or licensed audio). A user
can replace any of them by dropping `whoosh.wav`, `boom.wav` or `pop.wav` (or .mp3) in
`config/sounds.local/`. Music only comes from files the user puts in
`config/music.local/` (for example tracks from the YouTube Audio Library).
"""
import hashlib
import subprocess
from pathlib import Path

from video_editor import media
from video_editor.finishing import models
from video_editor.settings import BASE_DIR

SOUNDS_DIR = BASE_DIR / 'config' / 'sounds.local'
MUSIC_DIR = BASE_DIR / 'config' / 'music.local'
AUDIO_EXTENSIONS = ('.wav', '.mp3', '.m4a', '.ogg', '.flac')
KINDS = ('whoosh', 'boom', 'pop')
MIN_GAP = 0.6
# Mix levels relative to the voice, before mastering brings the whole mix to -14 LUFS.
EFFECT_VOLUME = {'whoosh': 0.30, 'boom': 0.55, 'pop': 0.35}
DEFAULT_MUSIC_DB = -24.0

# Short, dry effects: a filtered-noise swish, a pitch-dropping sub boom and a soft click.
SYNTH = {
    'whoosh': (
        'anoisesrc=d=0.55:c=pink:a=0.9:r=48000,'
        'highpass=f=350,lowpass=f=5500,'
        'afade=t=in:st=0:d=0.30:curve=qsin,afade=t=out:st=0.30:d=0.25:curve=qsin'
    ),
    'boom': (
        "aevalsrc='0.9*sin(2*PI*(70-35*t)*t)*exp(-2.6*t)':s=48000:d=1.1,"
        'lowpass=f=400'
    ),
    'pop': (
        "aevalsrc='0.8*sin(2*PI*820*t)*exp(-38*t)':s=48000:d=0.14,"
        'highpass=f=200'
    ),
}


def _ffmpeg(args):
    result = subprocess.run(
        [media.binary('ffmpeg'), '-nostdin', '-y', '-v', 'error', *args],
        capture_output=True, text=True, encoding='utf-8', errors='replace',
    )
    if result.returncode:
        raise RuntimeError(result.stderr[-2000:] or 'ffmpeg falhou.')


def _user_file(folder, stem):
    for extension in AUDIO_EXTENSIONS:
        path = Path(folder) / f'{stem}{extension}'
        if path.is_file():
            return path
    return None


def effect_file(kind, work_dir, sounds_dir=None):
    """The user's own file for this effect, or a synthesized one cached in work_dir."""
    if kind not in KINDS:
        raise ValueError(f'Efeito desconhecido: {kind!r}.')
    custom = _user_file(sounds_dir or SOUNDS_DIR, kind)
    if custom:
        return custom
    path = Path(work_dir) / 'sfx' / f'{kind}.wav'
    if not path.is_file():
        path.parent.mkdir(parents=True, exist_ok=True)
        _ffmpeg(['-f', 'lavfi', '-i', SYNTH[kind], '-ac', '2', '-ar', '48000', str(path)])
    return path


def default_sound(mode):
    """Effect for a layer of a hand-written plan, which carries no explicit choice."""
    if mode == 'badge' or mode == 'badge_big':
        return 'pop'
    if mode in ('fill', 'dark'):
        # Full-frame stills usually hide something (OBS, a private window): stay silent.
        return None
    return 'whoosh'


def events(plan):
    """(final time, effect) for every layer start, at least MIN_GAP apart."""
    cards = plan.cards
    raw = []
    for item in plan.overlays:
        kind = item.sound if item.sound is not None else default_sound(item.mode)
        if kind and kind != 'none':
            raw.append((models.map_time(item.start, cards), kind))
    for item in plan.banners:
        raw.append((models.map_time(item.start, cards), 'pop'))
    for card in cards:
        raw.append((models.card_start(card, cards), 'whoosh'))
    result = []
    for time, kind in sorted(raw):
        if result and time - result[-1][0] < MIN_GAP:
            continue
        result.append((round(time, 3), kind))
    return result


def music_file(option, seed, music_dir=None):
    """`option` is 'auto' (pick a track from the music folder), 'none' or a path."""
    if not option or option == 'none':
        return None
    if option != 'auto':
        path = Path(option)
        return path if path.is_file() else None
    folder = Path(music_dir or MUSIC_DIR)
    tracks = sorted(
        path for path in folder.glob('*') if path.suffix.lower() in AUDIO_EXTENSIONS
    ) if folder.is_dir() else []
    if not tracks:
        return None
    # Stable per video, varied across videos.
    index = int(hashlib.sha1(str(seed).encode()).hexdigest(), 16) % len(tracks)
    return tracks[index]


def mix(video_in, video_out, plan, duration, work_dir, seed='', sounds_dir=None, music_dir=None):
    """Add effects and ducked music to the audio of `video_in`; the video is copied.

    Returns what was added, or None when there was nothing to add (the caller keeps
    `video_in` as is).
    """
    # Only plans that ask for sound get it (the panel's plans do); older hand-written
    # plans keep rendering exactly as before.
    options = getattr(plan, 'sound', None)
    if not options or options.get('enabled') is False:
        return None
    options = dict(options)
    effect_events = events(plan) if options.get('effects', True) else []
    track = music_file(options.get('music', 'auto'), seed, music_dir)
    if not effect_events and track is None:
        return None
    inputs = ['-i', str(video_in)]
    graph = []
    buses = ['[voice]']
    used = sorted({kind for _, kind in effect_events})
    if track is not None:
        graph.append('[0:a]asplit=2[voice][key]')
    else:
        graph.append('[0:a]anull[voice]')
    stream = 1
    labels = []
    for kind in used:
        times = [time for time, item in effect_events if item == kind]
        inputs += ['-i', str(effect_file(kind, work_dir, sounds_dir))]
        split = ''.join(f'[{kind}{n}]' for n in range(len(times)))
        graph.append(f'[{stream}:a]aformat=sample_rates=48000:channel_layouts=stereo,'
                     f'asplit={len(times)}{split}')
        for n, time in enumerate(times):
            delay = int(round(time * 1000))
            label = f'[e{kind}{n}]'
            graph.append(f'[{kind}{n}]adelay={delay}|{delay},'
                         f'volume={EFFECT_VOLUME[kind]}{label}')
            labels.append(label)
        stream += 1
    if labels:
        graph.append(''.join(labels) + f'amix=inputs={len(labels)}:normalize=0[sfx]')
        buses.append('[sfx]')
    if track is not None:
        inputs += ['-stream_loop', '-1', '-i', str(track)]
        level = float(options.get('music_db', DEFAULT_MUSIC_DB))
        fade_out = max(0.0, duration - 3.0)
        graph.append(
            f'[{stream}:a]aformat=sample_rates=48000:channel_layouts=stereo,'
            f'atrim=0:{duration:.3f},asetpts=PTS-STARTPTS,volume={level}dB,'
            f'afade=t=in:st=0:d=2,afade=t=out:st={fade_out:.3f}:d=3[music]'
        )
        # The music ducks under the voice and comes back up in the pauses.
        graph.append('[music][key]sidechaincompress=threshold=0.02:ratio=10:'
                     'attack=20:release=450:makeup=1[ducked]')
        buses.append('[ducked]')
    graph.append(''.join(buses) + f'amix=inputs={len(buses)}:normalize=0:duration=first[aout]')
    _ffmpeg([
        *inputs, '-filter_complex', ';'.join(graph),
        '-map', '0:v?', '-map', '[aout]', '-c:v', 'copy',
        '-c:a', 'aac', '-b:a', '192k', '-ar', '48000',
        '-t', f'{duration:.6f}', '-movflags', '+faststart', str(video_out),
    ])
    return dict(effects=len(effect_events), music=str(track) if track else None)
